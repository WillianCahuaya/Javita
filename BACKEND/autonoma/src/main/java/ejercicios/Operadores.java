package ejercicios;

public class Operadores {

    public static void main(String[] args) {
        int num1, num2;
        num1 = 17;
        num2 = 20;
        int Resultado_suma;
        int Resultado_resta;

        Resultado_suma = num1 + num2;
        Resultado_resta = num2 - num1;

        System.out.println("Resultado Suma: " + Resultado_suma);
        System.out.println("Resultado Resta: " + Resultado_resta);

    }
}
